CREATE TABLE IF NOT EXISTS properties (
  id TEXT PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  purpose TEXT NOT NULL,
  location TEXT NOT NULL,
  county TEXT NOT NULL,
  type TEXT NOT NULL,
  beds INTEGER,
  baths INTEGER,
  size TEXT NOT NULL DEFAULT '',
  price_label TEXT NOT NULL,
  price_ksh INTEGER,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  image TEXT NOT NULL,
  gallery JSONB NOT NULL DEFAULT '[]'::jsonb,
  summary TEXT NOT NULL,
  description TEXT NOT NULL,
  features JSONB NOT NULL DEFAULT '[]'::jsonb,
  amenities JSONB NOT NULL DEFAULT '[]'::jsonb,
  status TEXT NOT NULL DEFAULT 'published',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_properties_status ON properties (status);
CREATE INDEX IF NOT EXISTS idx_properties_purpose ON properties (purpose);
CREATE INDEX IF NOT EXISTS idx_properties_location ON properties (location);

CREATE TABLE IF NOT EXISTS enquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id TEXT,
  property_ref TEXT,
  property_title TEXT,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  message TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'contact',
  status TEXT NOT NULL DEFAULT 'new',
  created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_enquiries_status ON enquiries (status);
CREATE INDEX IF NOT EXISTS idx_enquiries_created ON enquiries (created_at);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- The app uses the Postgres connection directly. These policies block the
-- public Supabase anon/authenticated APIs from reading or writing these tables.
ALTER TABLE properties ENABLE ROW LEVEL SECURITY;
ALTER TABLE enquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
